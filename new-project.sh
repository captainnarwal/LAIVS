#!/usr/bin/env bash
# Create a video project: ./new-project.sh [name]   |   ./new-project.sh --list
set -euo pipefail
cd "$(dirname "$0")"

if [ "${1:-}" = "--list" ]; then
  ls -1 projects | grep -v '^\.' || echo "(no projects yet)"; exit 0
fi

name="${1:-}"
[ -n "$name" ] || read -rp "Project name (e.g. my-product-ad): " name
name=$(echo "$name" | tr 'A-Z ' 'a-z-' | tr -cd 'a-z0-9-')
[ -n "$name" ] || { echo "Need a name with letters or digits."; exit 1; }
p="projects/$name"
[ ! -e "$p" ] || { echo "Project '$name' already exists."; exit 1; }

echo "== creating $p"
mkdir -p "$p"/{audio,timing,assets,out}
for d in brand images videos music sfx voice; do
  mkdir -p "$p/library/$d"; touch "$p/library/$d/.gitkeep"
done
cat > "$p/library/README.md" <<'MD'
# library/

This project's brand rules and raw media. Claude searches here before generating anything.

- `brand/` guidelines (`brand.md`) and tokens (`brand.json`).
- `images/ videos/ music/ sfx/ voice/` raw files you drop in.
- Each file `x.ext` gets a sidecar `x.ext.json` (see docs/guide/07-library.md).
- `catalog.json` is generated by `scripts/py scripts/library.py scan`. Do not edit.
MD
cat > "$p/library/brand/brand.md" <<MD
# $name brand guidelines

## Who we are
<company / product, one line>

## Voice and tone
<e.g. direct, friendly>

## Visual style
<colors, fonts, mood>

## Logo rules
<which logo on which background>
MD
cat > "$p/library/brand/brand.json" <<'JSON'
{
  "name": "<brand>",
  "colors": {"primary": "<#hex>", "accent": "<#hex>", "background": "<#hex>", "text": "<#hex>"},
  "fonts": {"heading": "<font>", "body": "<font>"},
  "logos": {},
  "tone": [],
  "default_format": {"width": 1920, "height": 1080, "fps": 30},
  "default_music": null
}
JSON
echo '{"scenes": []}' > "$p/script.json"
echo "$name" > projects/.current

echo "== done: $p (now the active project)"
echo "Add logos, music, footage to $p/library/ and fill in $p/library/brand/, then ask Claude to make your video."
